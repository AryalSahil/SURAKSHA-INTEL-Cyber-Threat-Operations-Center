// Deterministic coordinate calculation from event ID to ensure consistent radar positions
export function calculateRadarCoordinates(id: string): { angle: number; distance: number } {
  let hash = 0;
  for (let i = 0; i < id.length; i++) {
    hash = (hash << 5) - hash + id.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);
  const angle = positiveHash % 360;
  // Normalized distance from center (0.2 to 0.88)
  const distance = 0.2 + ((positiveHash >> 3) % 68) / 100;
  return { angle, distance };
}

